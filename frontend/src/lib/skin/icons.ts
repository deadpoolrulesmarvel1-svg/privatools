/** Names the designs reference that are absent from their own embedded fonts —
 *  these render as tofu in the original prototypes too. */
const FALLBACKS: Record<string, string> = {
    install_mobile: "download",
    cloud_queue: "cloud",
};

const BY_SKIN: Partial<Record<SkinId, IconMap>> = {
    aurora: AURORA_ICONS,
    carbon: CARBON_ICONS,
    structured: STRUCTURED_ICONS,
};

/**
 * Resolve a Material Symbols name to the character this skin's font carries.
 * Returns an empty string for an unknown name rather than leaking the raw name
 * into the UI as text, which is how a missing icon becomes a visible bug.
 */
export function skinIcon(skin: SkinId, name: string): string {
    const map = BY_SKIN[skin];
    if (!map) return "";
    return map[name] ?? map[FALLBACKS[name] ?? ""] ?? "";
}
